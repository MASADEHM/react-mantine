/**
 * Get service type by ID
 */
export const getServiceTypeById = (id: string): ServiceType | undefined => {
  return mockServiceTypes.find((service) => service.id === id);
};

/**
 * Get service types by category
 */
export const getServiceTypesByCategory = (category: string): ServiceType[] => {
  return mockServiceTypes.filter((service) => service.category === category && service.isActive);
};

/**
 * Get popular service types
 */
export const getPopularServiceTypes = (): ServiceType[] => {
  return mockServiceTypes.filter((service) => service.isPopular && service.isActive);
};

/**
 * Get all active service types
 */
export const getActiveServiceTypes = (): ServiceType[] => {
  return mockServiceTypes.filter((service) => service.isActive);
};
